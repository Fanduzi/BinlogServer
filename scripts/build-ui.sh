#!/usr/bin/env bash
# input: console/ (React Console) and frontend/ (classic Vue console) source trees, node toolchain, and build configuration dependencies
# output: console/dist synced into internal/ui/static (served at /ui/) and frontend/dist synced into internal/ui/classic (served at /ui-classic/ for one release), each JS chunk stamped with an L3 header, then check-ui-bundle.sh (ESM syntax and Console markers); shared locales (console/src/locales) compiled and Console unit tests run before the builds; npm ci when vite is missing
# pos: build pipeline bridge between frontend artifacts and backend embedded UI delivery
# note: if this file changes, update this header and module README.md.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
CONSOLE_DIR="$ROOT_DIR/console"
CLASSIC_DIR="$ROOT_DIR/frontend"
UI_STATIC_DIR="$ROOT_DIR/internal/ui/static"
UI_CLASSIC_DIR="$ROOT_DIR/internal/ui/classic"

ensure_deps() {
  if [[ ! -x "$1/node_modules/.bin/vite" ]]; then
    echo "[ui] vite not found in $1; running npm ci"
    (cd "$1" && npm ci)
  fi
}

echo "[ui] check locales (console/src/locales) and build classic console (base=/ui-classic/)"
ensure_deps "$CLASSIC_DIR"
(
  cd "$CLASSIC_DIR"
  npm run test:locales
  VITE_BASE=/ui-classic/ npm run build
)

echo "[ui] test and build Console (base=/ui/)"
ensure_deps "$CONSOLE_DIR"
(
  cd "$CONSOLE_DIR"
  npm test
  VITE_BASE=/ui/ npm run build
)

# sync_dist <dist> <target dir> <url prefix>
# Replaces the target's build output (README.md stays), then stamps the L3
# header with a byte copy. Do not interpolate the bundle. Leave a chunk alone
# when its JS body already matches, so a rebuild does not rewrite headers.
sync_dist() {
  local dist="$1" target="$2" prefix="$3" snap
  echo "[ui] sync ${dist#$ROOT_DIR/} -> ${target#$ROOT_DIR/}"
  mkdir -p "$target"
  snap="$(mktemp -d)"
  cp -a "$target/." "$snap/"
  find "$target" -mindepth 1 -maxdepth 1 ! -name README.md -exec rm -rf {} +
  [[ -f "$snap/assets/README.md" ]] && mkdir -p "$target/assets" && cp "$snap/assets/README.md" "$target/assets/README.md"
  cp -R "$dist/." "$target/"
  UI_DIST="$dist" UI_STATIC="$target" UI_SNAP="$snap" UI_PREFIX="$prefix" UI_README="${target#$ROOT_DIR/}/assets/README.md" node <<'JS'
const fs = require("fs");
const path = require("path");
const dist = process.env.UI_DIST;
const staticDir = process.env.UI_STATIC;
const snap = process.env.UI_SNAP;
const header = Buffer.from(
  [
    "// input: Vite-generated frontend modules and dependency chunks",
    "// output: browser-executable embedded UI bundle",
    `// pos: generated static asset served under ${process.env.UI_PREFIX}assets`,
    `// note: generated by make ui-build; update ${process.env.UI_README} if the layout changes.`,
    "",
    "",
  ].join("\n")
);
function stripHeader(buf) {
  let s = buf.toString("utf8");
  if (!s.startsWith("// input:")) return buf;
  while (s.startsWith("//") || s.startsWith("\n")) {
    if (s.startsWith("//")) {
      const nl = s.indexOf("\n");
      if (nl < 0) return Buffer.alloc(0);
      s = s.slice(nl + 1);
    } else {
      s = s.slice(1);
    }
  }
  return Buffer.from(s);
}
function walk(dir) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      walk(p);
      continue;
    }
    if (!ent.name.endsWith(".js")) continue;
    const rel = path.relative(dist, p);
    const dest = path.join(staticDir, rel);
    const fresh = fs.readFileSync(dest);
    const prevPath = path.join(snap, rel);
    if (fs.existsSync(prevPath)) {
      const prev = fs.readFileSync(prevPath);
      if (stripHeader(prev).equals(fresh)) {
        fs.writeFileSync(dest, prev);
        continue;
      }
    }
    fs.writeFileSync(dest, Buffer.concat([header, fresh]));
  }
}
walk(dist);
JS
  rm -rf "$snap"
}

sync_dist "$CONSOLE_DIR/dist" "$UI_STATIC_DIR" /ui/
sync_dist "$CLASSIC_DIR/dist" "$UI_CLASSIC_DIR" /ui-classic/

"$ROOT_DIR/scripts/check-ui-bundle.sh"

echo "[ui] done: /ui/ serves the Console, /ui-classic/ the classic console"
