import { chromium } from '@playwright/test'
import { BASE, CLASSIC, OUT } from './env.mjs'

const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
const calls = []
p.on('request', (r) => { const u = new URL(r.url()); if (u.pathname.startsWith('/api')) calls.push(`${r.method()} ${u.pathname}${u.search} auth=${r.headers()['authorization'] ? 'y' : 'n'}`) })
const errs = []; p.on('pageerror', (e) => errs.push(String(e)))
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1 }
await p.goto(BASE + '/')
await p.waitForSelector('[data-testid=settings-dialog]')
ok(p.url().endsWith('#/overview'), 'root redirects to #/overview (Vue default): ' + p.url())
ok(await p.getByText('需要重新认证').isVisible(), '401 shows re-auth banner + settings')
await p.screenshot({ path: `${OUT}/01-auth-required.png` })
await p.fill('[data-testid=settings-token-input]', 'ui302-test-token')
await p.getByRole('button', { name: '保存' }).click()
await p.waitForSelector('[data-testid=cluster-task-count]'); await p.goto(BASE + '/#/tasks'); await p.waitForSelector('[data-testid=task-row-2]')
ok(await p.evaluate(() => localStorage.getItem('binlog_server_token')) === 'ui302-test-token', 'token stored under binlog_server_token')
ok((await p.textContent('[data-testid=kpi-abnormal-value]')).trim() === '1', 'KPI abnormal=1')
ok((await p.locator('tbody tr').count()) === 20, 'page 1 has 20 rows')
ok((await p.textContent('[data-testid=task-filter-count]')).includes('26'), 'global total 26 shown')
await p.waitForTimeout(500)
await p.screenshot({ path: `${OUT}/02-tasks.png`, fullPage: true })
calls.length = 0
await p.getByRole('button', { name: '2', exact: true }).click()
await p.waitForTimeout(800)
ok((await p.locator('tbody tr').count()) === 6, 'page 2 has 6 rows')
console.log('page2 calls:', calls)
calls.length = 0
await p.click('[data-testid=pager-size]'); await p.getByRole('option', { name: '50条/页' }).click()
await p.waitForTimeout(800)
ok((await p.locator('tbody tr').count()) === 26, 'size 50 shows 26 rows')
console.log('size calls:', calls)
calls.length = 0
await p.fill('input[placeholder="按当前页任务 ID/名称搜索"]', 'orders')
await p.waitForTimeout(700)
ok((await p.locator('tbody tr').count()) === 3, 'keyword orders -> 3 rows (client-side)')
console.log('keyword calls:', calls)
await p.getByRole('button', { name: '重置筛选' }).click()
calls.length = 0
await p.click('[data-testid=filter-task-state]'); await p.getByRole('option', { name: /运行中|RUNNING/ }).first().click()
await p.waitForTimeout(800)
console.log('state calls:', calls)
ok(calls.some((c) => c.includes('state=RUNNING')), 'task state goes to server as state=RUNNING')
ok((await p.locator('tbody tr').count()) === 3, 'RUNNING -> 3 rows')
calls.length = 0
await p.click('[data-testid=kpi-abnormal]')
await p.waitForTimeout(800)
ok((await p.locator('tbody tr').count()) === 1, 'abnormal KPI -> 1 row')
await p.locator('[data-testid=task-row-1]').hover()
await p.click('[data-testid=view-nav-alerts]')
await p.waitForTimeout(800)
ok(p.url().endsWith('#/alerts'), 'alerts route')
ok((await p.locator('tbody tr').count()) === 1, 'alerts -> 1 row')
await p.screenshot({ path: `${OUT}/03-alerts.png`, fullPage: true })
await p.click('[data-testid=view-nav-overview]'); await p.waitForSelector('[data-testid=cluster-panel]')
ok(await p.getByTestId('cluster-task-count').innerText() === '26', 'overview cluster panel task count 26')
await p.goto(BASE + '/#/tasks?mode=alerts'); await p.waitForTimeout(800); ok(p.url().endsWith('#/alerts'), 'tasks?mode=alerts deep link -> alerts')
await p.evaluate(() => localStorage.setItem('locale', 'en')); await p.reload(); await p.waitForSelector('[data-testid=task-row-1]')
ok(await p.getByText('Binlog Server Operations Console').isVisible(), 'en locale')
await p.screenshot({ path: `${OUT}/04-tasks-en.png`, fullPage: true })
await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(400)
await p.screenshot({ path: `${OUT}/05-mobile.png`, fullPage: true })
ok(errs.length === 0, 'no page errors ' + errs.join(';'))
console.log('unique endpoints:', [...new Set(calls.map((c) => c.split('?')[0]))])
await b.close()
